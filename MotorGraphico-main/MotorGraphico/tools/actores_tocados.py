SOMBRA_ESPEJO = {"1": "3", "6": "8"}


def simetrico(fila0, mitades, sombra_derecha=True):
    """Plantilla de frente/espalda a partir de la mitad izquierda.

    Cada cadena cubre los indices 0..10 (x 22..32, el 10 es el eje x=32).
    La mitad derecha es su espejo; con sombra_derecha, la luz de la
    izquierda pasa a sombra a la derecha (luz desde la izquierda).
    """
    filas = []
    for m in mitades:
        if len(m) > 11:
            raise ValueError(f"mitad de {len(m)} caracteres (maximo 11, el 10 es el eje): {m!r}")
        m = m.ljust(11, ".")
        der = "".join(SOMBRA_ESPEJO.get(c, c) if sombra_derecha else c for c in reversed(m[:10]))
        filas.append((m + der).rstrip("."))
    return (fila0, filas)


