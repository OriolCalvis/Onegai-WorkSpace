# EditorAction (minusculas, como lo escribe EditorAyuda) -> icono.
ACCIONES = {
    "save": "guardar", "close": "cerrar", "quit": "salir", "undo": "deshacer",
    "redo": "rehacer", "paint": "pintar", "erase": "borrar", "fill": "rellenar",
    "playerstart": "inicio", "objects": "objetos", "removeobject": "borrar_objeto",
    "center": "centrar", "help": "ayuda", "layers": "capas",
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vista", action="store_true")
    ap.add_argument("--salida", default=str(TEX))
    args = ap.parse_args()
    salida = Path(args.salida)
    salida.mkdir(parents=True, exist_ok=True)

    ids = [i[0] for i in ICONOS]
    assert len(ids) == len(set(ids)), "ids repetidos"
    for v in ACCIONES.values():
        assert v in ids, v
    celda, columnas = gen_iconos.CELDA, gen_iconos.COLUMNAS
    filas = (len(ICONOS) + columnas - 1) // columnas
    atlas = Image.new("RGBA", (columnas * celda, filas * celda), (0, 0, 0, 0))
    frames = {}
    for n, icono in enumerate(ICONOS):
        c = Image.new("RGBA", (celda, celda), (0, 0, 0, 0))
        gen_iconos.pintar(icono, c)
        col, fila = n % columnas, n // columnas
        atlas.paste(c, (col * celda, fila * celda))
        frames[icono[0]] = {"frame": n + 1, "col": col, "row": fila, "nombre": icono[1]}
    atlas.save(salida / "iconos_editor.png")
    manifiesto = {
        "_nota": "Atlas de iconos del editor (motor_editor). Generado por tools/gen_iconos_editor.py: no editar a mano. Frames 1-based por filas; TextureManager invierte el PNG al cargarlo (misma regla que iconos.json).",
        "estado": "runtime",
        "generador": "tools/gen_iconos_editor.py",
        "image": "iconos_editor.png",
        "frameSize": [celda, celda],
        "columns": columnas,
        "rows": filas,
        "iconos": frames,
        "acciones": ACCIONES,
    }
    with open(salida / "iconos_editor.json", "w", encoding="utf-8") as f:
        json.dump(manifiesto, f, ensure_ascii=False, indent=1)
        f.write("\n")
    if args.vista:
        out = ROOT / "out"
        out.mkdir(exist_ok=True)
        grande = atlas.resize((atlas.width * 4, atlas.height * 4), Image.NEAREST)
        fondo = Image.new("RGBA", grande.size, (60, 60, 70, 255))
        fondo.alpha_composite(grande)
        fondo.save(out / "iconos_editor_vista.png")
    print(f"{len(ICONOS)} iconos -> {salida / 'iconos_editor.png'} ({atlas.width}x{atlas.height})")


if __name__ == "__main__":
    main()
