"""Peinados: plantillas por direccion para la ranura "pelo".

PELO_CORTO y PELO_LARGO estan dibujados a mano (actores_tocados). Los
demas se escriben como SILUETA y actores_siluetas pone los tonos; la
textura de cada peinado (mechones, rizos, greñas) es una funcion.
Todos se dibujan contra la cabeza del frame quieto del cuerpo base (la
cabeza no cambia entre tallas), asi que valen para las cuatro tallas.
"""
from actores_siluetas import espejo_mitad as em
from actores_siluetas import plantilla
from actores_tocados import PELO_CORTO, PELO_LARGO


def _mechones(y, x, tono, u, v):
    """Brillo en banda arriba a la izquierda y vetas verticales abajo."""
    if tono == "base" and 0.12 < v < 0.3 and u < 0.55:
        return "luz"
    if tono == "base" and v > 0.45 and x % 3 == 0:
        return "sombra"
    return tono


def _rizos(y, x, tono, u, v):
    if tono == "base" and y % 3 == 0 and (x + y // 3) % 3 == 0:
        return "luz" if u < 0.6 else "base"
    if tono == "base" and y % 3 == 2 and (x + y // 3) % 3 == 2:
        return "sombra"
    return tono


def _grenas(y, x, tono, u, v):
    """Mechones verticales desiguales y un brillo pequeno arriba."""
    if tono == "base" and v > 0.25 and (x + y // 4) % 3 == 0:
        return "sombra"
    if tono == "base" and 0.05 < v < 0.2 and u < 0.45 and x % 2 == 0:
        return "luz"
    return tono


def _peinado_atras(y, x, tono, u, v):
    """Pelo tirante: vetas que suben desde las sienes hacia el mono."""
    veta = (x + y) % 4 == 0 if x < 10 else (x - y) % 4 == 0
    if tono == "base" and veta and v > 0.15:
        return "sombra" if u > 0.35 else "luz"
    return tono


